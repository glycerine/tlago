// Native Go port of OpenJDK 21 GB18030 charset behavior used by JavaMail.
// Source: https://github.com/openjdk/jdk21u/blob/master/src/java.base/share/classes/sun/nio/cs/GB18030.java
// Range deltas retain the source tables' private-use mappings and 2022/2000
// selection on top of the pinned x/text v0.28.0 GB18030 mapping data. They were
// checked against installed OpenJDK 21.0.12.1 for every two-byte sequence,
// every BMP four-byte index, and every nonsurrogate BMP encoding.

package tlc

import (
	"sort"
	"strings"
	"sync"
	"unicode/utf8"
)

var mailGB18030Class struct {
	sync.Once
	old bool
}

func initializeMailGB18030() {
	mailGB18030Class.Do(func() { mailGB18030Class.old = tlcGetSystemProperty("jdk.charset.GB18030", "") == "2000" })
}

type mailGBRange struct{ first, last, value uint32 }

func mailGBLookup(ranges []mailGBRange, key uint32) (uint32, bool) {
	i := sort.Search(len(ranges), func(i int) bool { return ranges[i].last >= key })
	if i < len(ranges) && ranges[i].first <= key {
		return ranges[i].value + key - ranges[i].first, true
	}
	return 0, false
}
func mailGBSequence(data []byte) uint32 {
	if len(data) == 2 {
		return uint32(data[0])<<8 | uint32(data[1])
	}
	return 0x80000000 | (((uint32(data[0])-0x81)*10+uint32(data[1])-0x30)*126+uint32(data[2])-0x81)*10 + uint32(data[3]) - 0x30
}
func mailGBBytes(key uint32) []byte {
	if key < 0x80000000 {
		return []byte{byte(key >> 8), byte(key)}
	}
	key &= 0x7fffffff
	d := byte(key%10 + 0x30)
	key /= 10
	c := byte(key%126 + 0x81)
	key /= 126
	b := byte(key%10 + 0x30)
	key /= 10
	a := byte(key + 0x81)
	return []byte{a, b, c, d}
}
func encodeMailGB18030(value string) []byte {
	initializeMailGB18030()
	ranges := mailGBEncode2022[:]
	if mailGB18030Class.old {
		ranges = mailGBEncode2000[:]
	}
	encoder := mailCharsetEncoding("GB18030").NewEncoder()
	data := []byte{}
	for _, r := range mailPrintUTF8String(value) {
		if key, ok := mailGBLookup(ranges, uint32(r)); ok {
			data = append(data, mailGBBytes(key)...)
		} else {
			encoded, _ := encoder.Bytes([]byte(string(r)))
			data = append(data, encoded...)
		}
	}
	return data
}

// Keep JDK malformed-sequence widths at the native charset boundary; x/text
// consumes one byte for several GB18030 errors that Java consumes together.
func decodeMailGB18030(data []byte) string {
	initializeMailGB18030()
	ranges := mailGBDecode2022[:]
	if mailGB18030Class.old {
		ranges = mailGBDecode2000[:]
	}
	decoder := mailCharsetEncoding("GB18030").NewDecoder()
	var out strings.Builder
	for len(data) > 0 {
		if data[0] < 0x80 {
			out.WriteByte(data[0])
			data = data[1:]
			continue
		}
		width, malformed := 1, true
		if data[0] >= 0x81 && data[0] <= 0xfe && len(data) >= 2 {
			second := data[1]
			if second >= 0x30 && second <= 0x39 {
				width = 4
				if len(data) < width {
					width = len(data)
				} else if data[2] < 0x81 || data[2] > 0xfe {
					width = 3
				} else {
					malformed = data[3] < 0x30 || data[3] > 0x39
				}
			} else if second >= 0x30 {
				width = 2
				malformed = second < 0x40 || second == 0x7f || second == 0xff
			}
		}
		if !malformed && width == 4 {
			offset := mailGBSequence(data[:width]) & 0x7fffffff
			malformed = (offset > 0x99fb && offset < 0x2e248) || offset >= 0x12e248
		}
		if malformed {
			out.WriteRune(utf8.RuneError)
		} else if r, ok := mailGBLookup(ranges, mailGBSequence(data[:width])); ok {
			out.WriteRune(rune(r))
		} else {
			decoded, _ := decoder.Bytes(data[:width])
			out.Write(decoded)
		}
		data = data[width:]
	}
	return out.String()
}

